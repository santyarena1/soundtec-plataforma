import { buildSceneFromTemplate } from "@/services/room-builder/scene";
import { listRoomTemplates } from "@/services/room-builder/templates";
import { resizeSceneMeters } from "@/services/room-builder/dimensions";
import { layoutSceneDevices, sceneDims } from "@/services/room-builder/units";
const t = listRoomTemplates().find((x) => x.key === "residential-outdoor-m")!;
const base = buildSceneFromTemplate(t);
const withQty = { ...base, devices: base.devices.map((d) => ({ ...d, quantity: Math.max(1, d.quantity * 4) })) };
const scene = resizeSceneMeters(withQty, { widthM: Math.max(2.5, t.widthM * 0.6), depthM: Math.max(2.5, t.depthM * 0.6) });
const slots = new Map(scene.slots.map((s) => [s.key, s]));
for (const { device } of layoutSceneDevices(scene.devices, slots, sceneDims(scene))) if (device.slotKey === "speakers_outdoor") console.log(slots.get(device.slotKey), device.units?.map((u) => [u.pose.x, u.pose.y, u.pose.z, u.placed]));
console.log(scene.widthM, scene.depthM);
